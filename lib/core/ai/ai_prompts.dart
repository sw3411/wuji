/// 消费洞察维度定义。
class InsightDimension {
  const InsightDimension(
    this.id,
    this.title,
    this.systemPrompt, {
    this.needsRoster = false,
    this.needsDuplication = false,
    this.needsSold = false,
    this.needsIdle = false,
    this.needsMonthly = false,
  });

  final String id;
  final String title;
  final String systemPrompt;

  /// 需要物品明细清单（按价格降序）。
  final bool needsRoster;

  /// 需要同分类/同品牌的疑似重复分组。
  final bool needsDuplication;

  /// 需要已转卖物品明细（购价/卖价/净收入）。
  final bool needsSold;

  /// 需要闲置物品明细。
  final bool needsIdle;

  /// 需要近 6 个月月度数据。
  final bool needsMonthly;
}

